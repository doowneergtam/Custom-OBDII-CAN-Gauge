"""Minimal KiCad 8 board writer for the pod carrier.

Coordinates in this file are millimetres with the board centre at (0, 0)
and +y UP (as on the Waveshare drawing). KiCad's +y is down; the writer
flips y on output. Single copper layer on the back (B.Cu) for milling.
"""

class Board:
    def __init__(self, title):
        self.title = title
        self.nets = {"": 0}
        self.footprints = []
        self.tracks = []      # (points, width, net)
        self.outline = []     # raw s-expressions
        self.texts = []
        self.holes = []       # (x, y, drill)

    def net(self, name):
        if name not in self.nets:
            self.nets[name] = len(self.nets)
        return self.nets[name]

    # ---------------------------------------------------------- building
    def footprint(self, ref, value, lib, at, rot=0, pads=(), silk=(), desc="", top_ok=False):
        """pads: list of dict(name, x, y, shape, size, drill, net, layer). top_ok: a top-layer track may end on its pads."""
        for p in pads:
            self.net(p.get("net", ""))
        self.footprints.append(dict(ref=ref, value=value, lib=lib, at=at, rot=rot, pads=list(pads), silk=list(silk), desc=desc, top_ok=top_ok))

    def track(self, points, net, width=0.8, layer=0):
        """layer 0 = B.Cu (bottom, toward the Waveshare), 1 = F.Cu (top, parts side)."""
        self.net(net)
        self.tracks.append((points, width, net, layer))

    def hole(self, x, y, drill):
        self.holes.append((x, y, drill))

    def text(self, s, x, y, layer="B.SilkS", size=1.0, mirror=True, rot=0):
        self.texts.append((s, x, y, layer, size, mirror, rot))

    # ---------------------------------------------------------- output
    def _pad(self, p, fx, fy, frot):
        shape = p.get("shape", "circle")
        size = p.get("size", (1.8, 1.8))
        drill = p.get("drill", 1.0)
        layer = p.get("layer", "*.Cu")
        net = p.get("net", "")
        x, y = p["x"], p["y"]
        layers = '"*.Cu" "*.Mask"' if layer == "*.Cu" else f'"{layer}" "{layer[0]}.Mask"'
        kind = "thru_hole" if drill else "smd"
        drill_s = f" (drill {drill})" if drill else ""
        net_s = f' (net {self.nets[net]} "{net}")' if net else ""
        return (f'    (pad "{p["name"]}" {kind} {shape} (at {x} {-y} {frot}) (size {size[0]} {size[1]}){drill_s} '
                f'(layers {layers}){net_s})\n')

    def _footprint(self, f):
        x, y = f["at"]
        s = f'  (footprint "{f["lib"]}" (layer "F.Cu") (at {x} {-y} {f["rot"]})\n'
        s += f'    (property "Reference" "{f["ref"]}" (at 0 -2.5 {f["rot"]}) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))\n'
        s += f'    (property "Value" "{f["value"]}" (at 0 2.5 {f["rot"]}) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))\n'
        s += f'    (property "Description" "{f["desc"]}" (at 0 0 0) (layer "F.Fab") hide (effects (font (size 1 1) (thickness 0.15))))\n'
        for (x1, y1, x2, y2) in f["silk"]:
            s += f'    (fp_line (start {x1} {-y1}) (end {x2} {-y2}) (stroke (width 0.15) (type solid)) (layer "F.SilkS"))\n'
        for p in f["pads"]:
            s += self._pad(p, x, y, f["rot"])
        s += "  )\n"
        return s

    def write(self, path, diameter):
        out = []
        out.append('(kicad_pcb (version 20240108) (generator "nb1_gen") (generator_version "8.0")\n')
        out.append('  (general (thickness 1.6) (legacy_teardrops no))\n  (paper "A4")\n')
        out.append(f'  (title_block (title "{self.title}") (comment 1 "Generated by hardware/pcb/gen_pcb.py; single-sided, copper on B.Cu, for milling"))\n')
        out.append('  (layers (0 "F.Cu" signal) (31 "B.Cu" signal) (34 "B.Paste" user) (35 "F.Paste" user) (36 "B.SilkS" user "B.Silkscreen") (37 "F.SilkS" user "F.Silkscreen") (38 "B.Mask" user) (39 "F.Mask" user) (44 "Edge.Cuts" user) (46 "B.CrtYd" user) (47 "F.CrtYd" user) (48 "B.Fab" user) (49 "F.Fab" user))\n')
        out.append('  (setup (pad_to_mask_clearance 0.05) (pcbplotparams (layerselection 0x00010fc_ffffffff) (plot_on_all_layers_selection 0x0000000_00000000) (disableapertmacros no) (usegerberextensions yes) (usegerberattributes yes) (usegerberadvancedattributes yes) (creategerberjobfile yes) (dashed_line_dash_ratio 12.0) (dashed_line_gap_ratio 3.0) (svgprecision 4) (plotframeref no) (viasonmask no) (mode 1) (useauxorigin no) (hpglpennumber 1) (hpglpenspeed 20) (hpglpendiameter 15.0) (pdf_front_fp_property_popups yes) (pdf_back_fp_property_popups yes) (dxfpolygonmode yes) (dxfimperialunits yes) (dxfusepcbnewfont yes) (psnegative no) (psa4output no) (plotreference yes) (plotvalue yes) (plotfptext yes) (plotinvisibletext no) (sketchpadsonfab no) (subtractmaskfromsilk no) (outputformat 1) (mirror no) (drillshape 1) (scaleselection 1) (outputdirectory "gerbers/")))\n')
        for name, idx in sorted(self.nets.items(), key=lambda kv: kv[1]):
            out.append(f'  (net {idx} "{name}")\n')
        for f in self.footprints:
            out.append(self._footprint(f))
        r = diameter / 2
        out.append(f'  (gr_circle (center 0 0) (end {r} 0) (stroke (width 0.1) (type default)) (fill none) (layer "Edge.Cuts"))\n')
        for (x, y, d) in self.holes:
            out.append(f'  (footprint "MountingHole" (layer "F.Cu") (at {x} {-y})\n    (property "Reference" "H" (at 0 0) (layer "F.SilkS") hide (effects (font (size 1 1) (thickness 0.15))))\n    (pad "" np_thru_hole circle (at 0 0) (size {d} {d}) (drill {d}) (layers "*.Cu" "*.Mask"))\n  )\n')
        for tr in self.tracks:
            pts, w, net = tr[0], tr[1], tr[2]; lay = "F.Cu" if (len(tr) > 3 and tr[3] == 1) else "B.Cu"
            for (a, b) in zip(pts, pts[1:]):
                out.append(f'  (segment (start {a[0]} {-a[1]}) (end {b[0]} {-b[1]}) (width {w}) (layer "{lay}") (net {self.nets[net]}))\n')
        for (s, x, y, layer, size, mirror, rot) in self.texts:
            just = " (justify mirror)" if mirror else ""
            out.append(f'  (gr_text "{s}" (at {x} {-y} {rot}) (layer "{layer}") (effects (font (size {size} {size}) (thickness 0.15)){just}))\n')
        out.append(")\n")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("".join(out))


# ---------------------------------------------------------------- footprint helpers
def header_row(n, pitch=2.54, pad=2.25, drill=1.0, names=None, vertical=False, square_first=True):
    """1xN through-hole header, pin 1 at the negative end, centred."""
    pads = []
    for i in range(n):
        off = (i - (n - 1) / 2) * pitch
        pads.append(dict(name=str(i + 1), x=0 if vertical else off, y=off if vertical else 0,
                         shape="rect" if (i == 0 and square_first) else "circle",
                         size=(pad, pad), drill=drill, net=(names[i] if names else "")))
    return pads

def axial(span, pad=2.25, drill=1.0, nets=("", "")):
    return [dict(name="1", x=-span / 2, y=0, shape="rect", size=(pad, pad), drill=drill, net=nets[0]),
            dict(name="2", x=span / 2, y=0, shape="circle", size=(pad, pad), drill=drill, net=nets[1])]

def radial(pitch, pad=2.25, drill=1.0, nets=("", "")):
    return [dict(name="1", x=-pitch / 2, y=0, shape="rect", size=(pad, pad), drill=drill, net=nets[0]),
            dict(name="2", x=pitch / 2, y=0, shape="circle", size=(pad, pad), drill=drill, net=nets[1])]

def soic8(nets):
    """SOIC-8, pads on B.Cu (part mounted on the copper side, mirrored), 1.27 pitch."""
    pads = []
    for i in range(8):
        if i < 4:
            x, y = -1.905 + i * 1.27, -2.7
        else:
            x, y = 1.905 - (i - 4) * 1.27, 2.7
        pads.append(dict(name=str(i + 1), x=x, y=y, shape="rect", size=(0.9, 2.0), drill=0, layer="B.Cu", net=nets[i]))
    return pads

def dip4(nets, pitch=2.54, row=7.62):
    pads = []
    for i in range(4):
        x = -pitch / 2 + (i % 2) * pitch if False else None
    # DIP-4 (PC817): pins 1,2 on one side, 3,4 on the other
    coords = [(-pitch / 2, -row / 2), (pitch / 2, -row / 2), (pitch / 2, row / 2), (-pitch / 2, row / 2)]
    for i, (x, y) in enumerate(coords):
        pads.append(dict(name=str(i + 1), x=x, y=y, shape="rect" if i == 0 else "circle", size=(2.25, 2.25), drill=1.0, net=nets[i]))
    return pads


def smd2(span=3.2, pad=(1.5, 1.8), nets=("", ""), layer="F.Cu"):
    """Two-pad chip part (1206), horizontal, pin 1 at the negative end. layer F.Cu = parts side (top), B.Cu = bottom."""
    return [dict(name="1", x=-span / 2, y=0, shape="rect", size=pad, drill=0, layer=layer, net=nets[0]),
            dict(name="2", x=span / 2, y=0, shape="rect", size=pad, drill=0, layer=layer, net=nets[1])]
